#!/usr/bin/env python3
"""Check that a loadable module's undefined symbols exist in the kernel table.

Usage: libdl_check_module.py <nm> <rpi3_syms.c> <module.o|libmodule.a> ...

For every module, lists the symbols that `nm -u` reports as undefined and
that are NOT in the libdl symbol table generated by rtems-syms and trimmed
by libdl_syms_filter.py. Such a symbol makes dlopen() fail on the board
with "symbol not found", usually because --gc-sections removed it from the
kernel (nothing in the kernel uses it) or because the filter dropped it.
Fix: reference it from the kernel (-Wl,-u,<symbol> in rpi3_LDFLAGS) or
adjust the filter. Exit status 0 always; this is a build-time warning.
"""
import re
import subprocess
import sys


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    nm, table, modules = sys.argv[1], sys.argv[2], sys.argv[3:]
    with open(table) as f:
        exported = set(re.findall(r'\.asciz \\"([^"\\]+)\\"', f.read()))
    # Symbols defined by any of the given files (module objects and the
    # modules' libraries) satisfy each other: the loader resolves a
    # registration object's references from the library members it pulls
    # in (etc/libdl.conf), so only what neither they nor the kernel define
    # is really missing.
    for mod in modules:
        out = subprocess.run([nm, "--defined-only", "-g", mod], capture_output=True,
                             text=True, check=False).stdout
        exported.update(line.split()[-1] for line in out.splitlines()
                        if line.strip() and not line.endswith(":"))
    status = 0
    for mod in modules:
        try:
            out = subprocess.run([nm, "-u", mod], capture_output=True, text=True,
                                 check=False).stdout
        except OSError as e:
            print("libdl_check_module: %s: %s" % (mod, e))
            continue
        # archives: nm prints a "member.o:" header line per member, skip those
        undefined = sorted({line.split()[-1] for line in out.splitlines()
                            if line.strip() and not line.rstrip().endswith(":")})
        missing = [s for s in undefined if s not in exported]
        if missing:
            status = 1
            print("libdl_check_module: %s: %d undefined symbols, %d NOT in the kernel "
                  "table: %s" % (mod, len(undefined), len(missing), " ".join(missing)))
        else:
            print("libdl_check_module: %s: all %d undefined symbols are in the kernel "
                  "table" % (mod, len(undefined)))
    return status


if __name__ == "__main__":
    main()
